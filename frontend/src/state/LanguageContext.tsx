type LanguageContextValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};
const LanguageContext = createContext<LanguageContextValue | null>(null);
const localeByLanguage: Record<Language, string> = { en: "en-NG", ha: "ha-NG", yo: "yo-NG", ig: "ig-NG" };

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("govconnectx_language");
    return saved === "ha" || saved === "yo" || saved === "ig" ? saved : "en";
  });
  const setLanguage = useCallback((next: Language) => {
    localStorage.setItem("govconnectx_language", next);
    setLanguageState(next);
  }, []);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(() => ({
    language,
    locale: localeByLanguage[language],
    setLanguage,
    t: (key: string) => dictionaries[language][key] ?? key,
  }), [language, setLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
